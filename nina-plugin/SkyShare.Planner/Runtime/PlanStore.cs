using System;
using System.Collections.Generic;
using System.Linq;
using NINA.Sequencer.Conditions;
using NINA.Sequencer.Container;
using NINA.Sequencer.SequenceItem.FilterWheel;
using NINA.Sequencer.SequenceItem.FlatDevice;
using NINA.Sequencer.SequenceItem.Imaging;
using SkyShare.Planner.Core;

namespace SkyShare.Planner.Runtime {

    /// <summary>
    /// Shared state for one night, set by "SkyShare: Load Plan" and read by the
    /// Targets / Flats containers. One NINA instance runs one sequence at a time,
    /// so a process-wide store is sufficient.
    /// </summary>
    public static class PlanStore {
        private static readonly object Gate = new();
        private static readonly Dictionary<ISequenceContainer, int> TargetIndexByBlock = new();
        private static readonly Dictionary<int, double> MechanicalByIndex = new();
        private static readonly List<(TrainedFlatExposure item, FlatSpec spec, double rotation)> FlatItems = new();
        private static readonly List<string> FlatsSkipped = new();

        public static NightPlan? Plan { get; private set; }
        public static string? PlanPath { get; private set; }
        public static DateTime LoadedAt { get; private set; }

        public static void Set(NightPlan plan, string path) {
            lock (Gate) {
                Plan = plan;
                PlanPath = path;
                LoadedAt = DateTime.Now;
                TargetIndexByBlock.Clear();
                MechanicalByIndex.Clear();
                FlatItems.Clear();
                FlatsSkipped.Clear();
            }
        }

        public static NightPlan Require() =>
            Plan ?? throw new PlanException("No plan loaded. Put 'SkyShare: Load Plan' at the start of the sequence.");

        // --- target blocks generated by SkyShareTargets ---------------------

        public static void RegisterTargetBlock(ISequenceContainer block, int index) {
            lock (Gate) TargetIndexByBlock[block] = index;
        }

        public static void ClearTargetBlocks() {
            lock (Gate) { TargetIndexByBlock.Clear(); MechanicalByIndex.Clear(); }
        }

        /// <summary>Walks up from any item to the generated target block it lives in.</summary>
        public static int? FindTargetIndex(NINA.Sequencer.SequenceItem.ISequenceItem item) {
            lock (Gate) {
                for (ISequenceContainer? p = item.Parent; p != null; p = p.Parent)
                    if (TargetIndexByBlock.TryGetValue(p, out var i)) return i;
            }
            return null;
        }

        public static void RecordMechanicalPosition(int index, double mechanical) {
            lock (Gate) MechanicalByIndex[index] = mechanical;
        }

        /// <summary>
        /// What happened to each target tonight. "Ran" = at least one light frame
        /// completed (any SmartExposure loop advanced), which is what flats care about.
        /// </summary>
        public static IReadOnlyDictionary<int, TargetRunRecord> RunRecords() {
            lock (Gate) {
                return TargetIndexByBlock.ToDictionary(
                    kv => kv.Value,
                    kv => new TargetRunRecord(
                        Ran: SequenceTree.Descendants<SmartExposure>(kv.Key)
                                .SelectMany(se => se.Conditions.OfType<LoopCondition>())
                                .Any(lc => lc.CompletedIterations > 0),
                        MechanicalPosition: MechanicalByIndex.TryGetValue(kv.Value, out var m) ? m : null));
            }
        }
    
        /// <summary>Frames completed per target per filter (for the session manifest).</summary>
        public static IReadOnlyDictionary<int, IReadOnlyDictionary<string, int>> LightCounts() {
            lock (Gate) {
                return TargetIndexByBlock.ToDictionary(
                    kv => kv.Value,
                    kv => (IReadOnlyDictionary<string, int>)SequenceTree.Descendants<SmartExposure>(kv.Key)
                        .Select(se => (
                            filter: se.Items.OfType<SwitchFilter>().FirstOrDefault()?.Filter?.Name ?? "?",
                            done: se.Conditions.OfType<LoopCondition>().Sum(lc => lc.CompletedIterations)))
                        .GroupBy(x => x.filter, StringComparer.OrdinalIgnoreCase)
                        .ToDictionary(g => g.Key, g => g.Sum(x => x.done)));
            }
        }

        // --- flats generated by SkyShareFlats -------------------------------

        public static void SetFlats(IEnumerable<(TrainedFlatExposure item, FlatSpec spec, double rotation)> items,
                                    IEnumerable<string> skipped) {
            lock (Gate) {
                FlatItems.Clear(); FlatItems.AddRange(items);
                FlatsSkipped.Clear(); FlatsSkipped.AddRange(skipped);
            }
        }

        public static (IReadOnlyList<FlatSetResult> sets, IReadOnlyList<string> skipped) FlatResults() {
            lock (Gate) {
                var sets = FlatItems.Select(f => new FlatSetResult(
                    f.spec, f.rotation,
                    // Trained Flat Exposure keeps its loop on an inner container
                    SequenceTree.Descendants<ISequenceContainer>(f.item).Prepend(f.item)
                        .SelectMany(c => SequenceTree.Conditions(c).OfType<LoopCondition>())
                        .Sum(lc => lc.CompletedIterations))).ToList();
                return (sets, FlatsSkipped.ToList());
            }
        }
    }
}
